func TestGeneratedFileFilter_KeepOnMissingFile(t *testing.T) {
	t.Parallel()

	fsys := fstest.MapFS{}

	opt, err := gogenfilter.WithFilterOptions(gogenfilter.FilterAll)
	if err != nil {
		t.Fatalf("WithFilterOptions() error = %v", err)
	}

	gf, err := NewGeneratedFileFilter(
		nil,
		opt,
		gogenfilter.WithFS(fsys),
	)
	if err != nil {
		t.Fatalf("NewGeneratedFileFilter() error = %v", err)
	}

	findings := []finding.Finding{
		{ID: "1", Position: finding.Position{File: "missing.go"}},
	}

	result, err := gf.Process(t.Context(), findings)
	if err != nil {
		t.Fatalf("Process() error = %v", err)
	}

	if len(result) != 1 {
		t.Fatalf("Process() = %d findings, want 1", len(result))
	}

	if result[0].ID != "1" {
		t.Fatalf("Process() ID = %q, want %q", result[0].ID, "1")
	}
}

func sliceEqual(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}

	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}

	return true
}

