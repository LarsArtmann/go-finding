func TestGeneratedFileFilter_Disabled(t *testing.T) {
	t.Parallel()

	gf, err := NewGeneratedFileFilter(nil)
	if err != nil {
		t.Fatalf("NewGeneratedFileFilter() error = %v", err)
	}

	findings := []finding.Finding{
		{ID: "1", Position: finding.Position{File: "a.go"}},
		{ID: "2", Position: finding.Position{File: "b.go"}},
	}

	result, err := gf.Process(t.Context(), findings)
	if err != nil {
		t.Fatalf("Process() error = %v", err)
	}

	if len(result) != 2 {
		t.Fatalf("Process() = %d findings, want 2", len(result))
	}
}

func TestGeneratedFileFilter_FiltersGeneratedFiles(t *testing.T) {
	t.Parallel()

	fsys := fstest.MapFS{
		"gen/mock.go":      {Data: []byte("// Code generated by mockgen. DO NOT EDIT.\npackage main\n")},
		"gen/query.sql.go": {Data: []byte("// Code generated by sqlc. DO NOT EDIT.\npackage main\n")},
		"cmd/main.go":      {Data: []byte("package main\n\nfunc main() {}\n")},
	}

	opt, err := gogenfilter.WithFilterOptions(gogenfilter.FilterAll)
	if err != nil {
		t.Fatalf("WithFilterOptions() error = %v", err)
	}

	gf, err := NewGeneratedFileFilter(
		nil,
		opt,
		gogenfilter.WithFS(fsys),
	)
	if err != nil {
		t.Fatalf("NewGeneratedFileFilter() error = %v", err)
	}

	findings := []finding.Finding{
		{ID: "1", Position: finding.Position{File: "gen/mock.go"}},
		{ID: "2", Position: finding.Position{File: "gen/query.sql.go"}},
		{ID: "3", Position: finding.Position{File: "cmd/main.go"}},
		{ID: "4", Position: finding.Position{File: ""}},
	}

	result, err := gf.Process(t.Context(), findings)
	if err != nil {
		t.Fatalf("Process() error = %v", err)
	}

	if len(result) != 2 {
		t.Fatalf("Process() = %d findings, want 2", len(result))
	}

	ids := make([]string, len(result))
	for i, f := range result {
		ids[i] = f.ID
	}

	want := []string{"3", "4"}
	if !sliceEqual(ids, want) {
		t.Fatalf("Process() IDs = %v, want %v", ids, want)
	}
}

